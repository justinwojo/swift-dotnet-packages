using System.Text;
using Nuke.Common.IO;
using SwiftBindings.Build.Models;

partial class Build
{
    // ═══════════════════════════════════════════════════════════════════════
    //  Lane evidence: what the RUNNING app says about itself.
    //
    //  Both new lanes in this file's orbit — the release-consumption lane
    //  (Build.ReleaseConsumption.cs) and the Mono full-AOT device cell
    //  (Build.RegressionValidate.cs) — are distinguished from an ordinary test
    //  run by nothing the app itself can see: a rewritten reference, an
    //  MSBuild property. If either silently stops taking effect, the app still
    //  builds, installs, launches and goes green while establishing nothing.
    //
    //  So the harness injects one generated source file carrying a module
    //  initializer that prints, from inside the process, the runtime that is
    //  executing and the identity of every SwiftBindings assembly it loads.
    //  LaneEvidenceGate judges those lines. The injection rides the shared
    //  <Directory.Build.targets> hook (-p:SwiftBindingsLaneProps=<file>), so no
    //  test csproj and no test source has to know a lane exists.
    // ═══════════════════════════════════════════════════════════════════════

    internal const string LanePropsFileName = "lane.g.props";
    internal const string LaneEvidenceFileName = "LaneEvidence.g.cs";

    /// <summary>
    /// The generated probe compiled into a lane's test app. Deliberately
    /// dependency-free and fully qualified: it is compiled into every TFM a
    /// test app declares (iOS, tvOS, macOS, MacCatalyst), under
    /// <c>ImplicitUsings</c> and <c>Nullable</c> settings it does not control,
    /// and it must never be the reason a lane build fails.
    ///
    /// <para><b>MonoRuntime</b> is read from the presence of MonoVM's own
    /// corlib types rather than from <c>RuntimeFeature</c>: on a physical
    /// device, Mono full-AOT and NativeAOT both report dynamic code as
    /// unsupported, so a RuntimeFeature heuristic would label every Mono
    /// full-AOT run NativeAOT — the precise false green the Mono cell exists to
    /// prevent. The raw signals are printed alongside it so a future runtime
    /// change is diagnosable from the log rather than silently mis-judged.</para>
    /// </summary>
    internal static string LaneEvidenceSource() =>
        """
        // <auto-generated>
        //   Emitted by the Nuke harness (build/Build.LaneEvidence.cs) for a lane-evidence run.
        //   Not part of the repository; regenerated per run under artifacts/.
        // </auto-generated>
        #nullable enable

        internal static class SwiftBindingsLaneEvidenceProbe
        {
            private const string Prefix = "[lane-evidence] ";

            [System.Runtime.CompilerServices.ModuleInitializer]
            internal static void Emit()
            {
                try
                {
                    System.Console.WriteLine(Prefix + "runtime: " + DescribeRuntime());

                    foreach (var loaded in System.AppDomain.CurrentDomain.GetAssemblies())
                        Report(loaded);

                    // Assemblies resolve lazily under Mono, so the interesting
                    // ones are usually not loaded yet at module-init time.
                    System.AppDomain.CurrentDomain.AssemblyLoad += (_, e) => Report(e.LoadedAssembly);

                    // A referenced package the suite never touches would otherwise
                    // stay unloaded, and the consumption lane would reject a
                    // package the app really does reference. Load each direct
                    // SwiftBindings reference once so its identity is reported.
                    foreach (var referenced in System.Reflection.Assembly.GetExecutingAssembly().GetReferencedAssemblies())
                    {
                        if (referenced.Name is null || !referenced.Name.StartsWith("SwiftBindings", System.StringComparison.Ordinal))
                            continue;
                        try
                        {
                            Report(System.Reflection.Assembly.Load(referenced));
                        }
                        catch (System.Exception ex)
                        {
                            System.Console.WriteLine(Prefix + "assembly-error: " + referenced.Name + ": " + ex.GetType().Name + ": " + ex.Message);
                        }
                    }

                    // A package can be deployed beside the app without a static
                    // reference the linker keeps (Stripe's umbrella and UICore).
                    // Load every SwiftBindings assembly that actually shipped in
                    // the bundle so the consumption lane sees those too.
                    var bundleDir = System.AppContext.BaseDirectory;
                    if (!string.IsNullOrEmpty(bundleDir) && System.IO.Directory.Exists(bundleDir))
                    {
                        foreach (var file in System.IO.Directory.GetFiles(bundleDir, "SwiftBindings*.dll"))
                        {
                            try
                            {
                                Report(System.Reflection.Assembly.LoadFrom(file));
                            }
                            catch (System.Exception ex)
                            {
                                System.Console.WriteLine(Prefix + "assembly-error: " + file + ": " + ex.GetType().Name + ": " + ex.Message);
                            }
                        }
                    }
                }
                catch (System.Exception ex)
                {
                    System.Console.WriteLine(Prefix + "probe-error: " + ex.GetType().Name + ": " + ex.Message);
                }
            }

            private static string DescribeRuntime()
            {
                var mono = System.Type.GetType("Mono.Runtime") is not null
                    || System.Type.GetType("Mono.RuntimeStructs") is not null
                    || System.Type.GetType("Mono.RuntimeMarshal") is not null;

                return "MonoRuntime=" + mono
                    + " DynamicCodeSupported=" + System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported
                    + " DynamicCodeCompiled=" + System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeCompiled
                    + " Framework=\"" + System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription + "\"";
            }

            private static void Report(System.Reflection.Assembly assembly)
            {
                try
                {
                    var name = assembly.GetName();
                    if (name.Name is null || !name.Name.StartsWith("SwiftBindings", System.StringComparison.Ordinal))
                        return;

                    string informational;
                    try
                    {
                        var attribute = (System.Reflection.AssemblyInformationalVersionAttribute?)
                            System.Attribute.GetCustomAttribute(
                                assembly, typeof(System.Reflection.AssemblyInformationalVersionAttribute));
                        informational = attribute?.InformationalVersion ?? "(none)";
                    }
                    catch
                    {
                        informational = "(unavailable)";
                    }

                    // A NativeAOT/single-file app has no on-disk assembly, so
                    // Location is empty by design there and the probe reports
                    // "(none)". The warning is the trimmer telling us that; it
                    // is the expected answer for one of the two device lanes,
                    // and a device publish should not carry a warning for it.
        #pragma warning disable IL3000
                    var location = "(none)";
                    try
                    {
                        if (!string.IsNullOrEmpty(assembly.Location))
                            location = assembly.Location;
                    }
                    catch
                    {
                        location = "(unavailable)";
                    }
        #pragma warning restore IL3000

                    System.Console.WriteLine(
                        Prefix + "assembly: " + name.Name
                        + " version=" + (name.Version?.ToString() ?? "(none)")
                        + " informational=" + informational.Replace(' ', '_')
                        + " location=" + location);
                }
                catch (System.Exception ex)
                {
                    System.Console.WriteLine(Prefix + "assembly-error: " + ex.GetType().Name + ": " + ex.Message);
                }
            }
        }
        """;

    /// <summary>
    /// Render the lane props file imported by the repo-root
    /// <c>Directory.Build.targets</c> hook.
    ///
    /// <para><paramref name="swaps"/> turns the test app into a package
    /// consumer: each entry removes the <c>ProjectReference</c> exactly as the
    /// csproj spells it and adds the matching <c>PackageReference</c>. The
    /// Remove item spec is written verbatim because relative item paths in an
    /// imported file resolve against the importing PROJECT's directory, so the
    /// two identities are the same string against the same base.</para>
    ///
    /// <para>An empty <paramref name="swaps"/> is the evidence-only shape used
    /// by the Mono full-AOT device cell, which keeps its ProjectReferences.</para>
    ///
    /// <para><paramref name="workingTreeRoot"/>/<paramref name="laneScratchRoot"/>
    /// turn the app into a package consumer for NATIVE code too. Swapping the
    /// managed reference does nothing about the frameworks a test csproj embeds
    /// by relative path (<c>../X.xcframework</c>, and inside a target
    /// <c>../X/obj/…/XSwiftBindings.xcframework</c>) — NativeReference does not
    /// propagate through a ProjectReference, so every such csproj names them
    /// itself. The release workflow source-builds before this lane, so those
    /// artifacts exist and would link in place of the package's. The generated
    /// target drops exactly the items that resolve into the checkout and leaves
    /// the ones the lane itself produced (the package cache, and the SDK's own
    /// unpack of a binding package's <c>resources.zip</c> under the lane's obj/)
    /// alone. It runs at execution time rather than as a static Remove because
    /// the wrapper items are added by a target, not by an ItemGroup, and are not
    /// there to be removed at evaluation.</para>
    /// </summary>
    internal static string RenderLanePropsXml(
        IReadOnlyList<(string Include, string PackageId, string Version)> swaps,
        string? evidenceSourcePath,
        string? workingTreeRoot = null,
        string? laneScratchRoot = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("<Project>");
        sb.AppendLine("  <!-- Generated by the Nuke harness (build/Build.LaneEvidence.cs). Do not edit. -->");

        if (swaps.Count > 0)
        {
            sb.AppendLine("  <ItemGroup>");
            foreach (var (include, _, _) in swaps)
                sb.AppendLine($"    <ProjectReference Remove=\"{Attr(include)}\" />");
            foreach (var (_, id, version) in swaps)
                sb.AppendLine($"    <PackageReference Include=\"{Attr(id)}\" Version=\"{Attr(version)}\" />");
            sb.AppendLine("  </ItemGroup>");
        }

        if (swaps.Count > 0 && !string.IsNullOrEmpty(workingTreeRoot) && !string.IsNullOrEmpty(laneScratchRoot))
        {
            sb.AppendLine($"""
                  <PropertyGroup>
                    <_SwiftBindingsLaneWorkingTreeRoot>{Attr(WithTrailingSeparator(workingTreeRoot!))}</_SwiftBindingsLaneWorkingTreeRoot>
                    <_SwiftBindingsLaneScratchRoot>{Attr(WithTrailingSeparator(laneScratchRoot!))}</_SwiftBindingsLaneScratchRoot>
                  </PropertyGroup>
                  <Target Name="_SwiftBindingsLaneDropWorkingTreeNativeReferences"
                          BeforeTargets="ResolveNativeReferences">
                    <ItemGroup>
                      <_SwiftBindingsLaneWorkingTreeNative Include="@(NativeReference)"
                        Condition="$([System.String]::Copy('%(FullPath)').StartsWith('$(_SwiftBindingsLaneWorkingTreeRoot)')) and !$([System.String]::Copy('%(FullPath)').StartsWith('$(_SwiftBindingsLaneScratchRoot)'))" />
                      <NativeReference Remove="@(_SwiftBindingsLaneWorkingTreeNative)" />
                    </ItemGroup>
                    <Message Importance="High"
                             Condition="'@(_SwiftBindingsLaneWorkingTreeNative)' != ''"
                             Text="[lane] package mode: dropped working-tree NativeReference @(_SwiftBindingsLaneWorkingTreeNative->'%(Identity)', ', ')" />
                  </Target>
                """);
        }

        if (!string.IsNullOrEmpty(evidenceSourcePath))
        {
            sb.AppendLine("  <ItemGroup>");
            sb.AppendLine($"    <Compile Include=\"{Attr(evidenceSourcePath)}\" />");
            sb.AppendLine("  </ItemGroup>");
        }

        sb.AppendLine("</Project>");
        return sb.ToString();
    }

    /// <summary>
    /// XML-escape a value being written into a double-quoted attribute. Every
    /// value here is a path, a package id or a version that came from a
    /// checkout location or a CLI argument, so a directory containing
    /// <c>&amp;</c> or <c>"</c> would otherwise emit a malformed props file and
    /// the lane would die during project evaluation instead of validating the
    /// binding.
    ///
    /// <para>MSBuild's own item-spec metacharacters (<c>%</c>, <c>;</c>, <c>*</c>)
    /// are deliberately left alone: escaping those would change which files the
    /// item spec matches, and the ProjectReference Remove has to be the same
    /// string the csproj wrote.</para>
    /// </summary>
    static string Attr(string value) =>
        value
            .Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal)
            .Replace("\"", "&quot;", StringComparison.Ordinal)
            .Replace("'", "&apos;", StringComparison.Ordinal);

    /// <summary>
    /// A directory prefix that cannot half-match a sibling: without the trailing
    /// separator, <c>/repo/libraries</c> also prefixes <c>/repo/libraries-old</c>.
    /// </summary>
    static string WithTrailingSeparator(string path) =>
        path.EndsWith(Path.DirectorySeparatorChar) ? path : path + Path.DirectorySeparatorChar;

    /// <summary>
    /// Write <see cref="LaneEvidenceFileName"/> + <see cref="LanePropsFileName"/>
    /// into <paramref name="dir"/> and return the props path to pass as
    /// <c>-p:SwiftBindingsLaneProps=</c>.
    /// </summary>
    internal static AbsolutePath WriteLaneProps(
        AbsolutePath dir,
        IReadOnlyList<(string Include, string PackageId, string Version)> swaps,
        bool withEvidence,
        string? workingTreeRoot = null,
        string? laneScratchRoot = null)
    {
        dir.CreateDirectory();

        string? evidencePath = null;
        if (withEvidence)
        {
            var source = dir / LaneEvidenceFileName;
            File.WriteAllText(source, LaneEvidenceSource());
            evidencePath = source;
        }

        var props = dir / LanePropsFileName;
        File.WriteAllText(props, RenderLanePropsXml(swaps, evidencePath, workingTreeRoot, laneScratchRoot));
        return props;
    }

    /// <summary>
    /// Fail when a run's own output contradicts the runtime its lane launched.
    /// A run that printed no evidence line at all is a hard failure for lanes
    /// that injected the probe — the harness controls the injection, so silence
    /// means the injection did not take effect, which is exactly the masquerade
    /// this gate exists to catch. Callers must only reach this after the run
    /// itself succeeded, so an app that died before the banner is reported as
    /// the crash it was.
    /// </summary>
    internal static void AssertRuntimeFlavor(string? output, bool expectMono, string laneLabel)
    {
        var verdict = LaneEvidenceGate.JudgeRuntime(output, expectMono);
        var banner = LaneEvidenceGate.ExtractRuntimeBanner(output);

        switch (verdict)
        {
            case LaneEvidenceGate.Verdict.Match:
                Serilog.Log.Information("{Lane}: live runtime confirmed ({Body})", laneLabel, banner);
                return;
            case LaneEvidenceGate.Verdict.Mismatch:
                throw new InvalidOperationException(
                    LaneEvidenceGate.RuntimeMismatchMessage(laneLabel, banner!, expectMono));
            default:
                throw new InvalidOperationException(
                    $"{laneLabel}: the app ran to completion but printed no lane-evidence runtime line. " +
                    "The generated probe was not compiled in (check -p:SwiftBindingsLaneProps and the " +
                    "repo-root Directory.Build.targets hook), so this run proves nothing about the " +
                    "runtime it claims to have exercised.");
        }
    }
}
